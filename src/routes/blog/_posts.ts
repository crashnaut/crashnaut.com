import * as fs from "fs"
import { ISODate } from "#lib/formatters.ts"
import { variables } from "#lib/variables.ts"
import {
  parseFileToHtmlAndMeta,
  sortByDate,
  traverseFolder,
} from "#lib/markdown.ts"
import type { Post, PostMetadata } from "#lib/models.ts"

const blogPath = "blog"
const WORDS_PER_MINUTE = 230

const posts: Post[] = []

export async function readPosts(): Promise<Post[]> {
  if (posts.length) {
    return posts
  }
  console.log("\x1b[35m[posts] generate\x1b[0m")

  const folderContent = [...traverseFolder(blogPath, ".md")]
  const directories = folderContent.reduce(
    (dirs, file) => {
      dirs[file.folder] = [
        ...(dirs[file.folder] || []),
        { path: file.path, file: file.file },
      ]
      return dirs
    },
    {} as Record<string, { file: string; path: string }[]>,
  )

  const postsSorted = Object.values(directories)
    .map((files) => {
      const postPath = files.find((f) => f.file === "index.md")?.path
      if (!postPath) {
        throw new Error(`[posts] ${files[0].path}: folder has no index.md`)
      }
      const tldrPath = files.find((f) => f.file === "tldr.md")?.path

      const { html, metadata } = parseFileToHtmlAndMeta(postPath)
      const { html: tldr } = tldrPath
        ? parseFileToHtmlAndMeta(tldrPath)
        : { html: null }

      const slug = metadata.slug as string
      // Only an explicit `updated:` in frontmatter counts as a content update;
      // formatting commits shouldn't make every post look freshly modified.
      const updated = metadata.updated as string | Date | undefined
      const publishedAt = toISO(metadata.date)
      const modifiedAt = updated ? toISO(updated) : publishedAt

      const postMetadata: PostMetadata = {
        title: metadata.title as string,
        slug,
        description: (metadata.description as string) ?? "",
        author: (metadata.author as string) ?? "Mike Sell",
        date: ISODate(metadata.date as string),
        modified: updated ? ISODate(updated) : null,
        publishedAt,
        modifiedAt,
        tags: metadata.tags,
        banner: ogImageFor(slug),
        canonical: `${variables.basePath}/blog/${slug}`,
        readingMinutes: readingMinutes(html),
        outgoingLinks: [],
        incomingLinks: [],
        toc: metadata.toc,
        outgoingSlugs: metadata.outgoingSlugs,
      }

      return { html, tldr, metadata: postMetadata }
    })
    .sort(sortByDate)

  for (const post of postsSorted) {
    const linkTo = (p: Post) => ({
      slug: p.metadata.slug,
      title: p.metadata.title,
    })
    post.metadata.incomingLinks.push(
      ...postsSorted
        .filter((p) => p.metadata.outgoingSlugs?.includes(post.metadata.slug))
        .map(linkTo),
    )
    post.metadata.outgoingLinks.push(
      ...postsSorted
        .filter((p) => post.metadata.outgoingSlugs?.includes(p.metadata.slug))
        .map(linkTo),
    )
  }

  posts.push(...postsSorted)
  return postsSorted
}

/** Generated by `npm run og`; falls back to the site card if a post has none yet. */
export function ogImageFor(slug: string) {
  return fs.existsSync(`static/og/${slug}.png`)
    ? `${variables.basePath}/og/${slug}.png`
    : `${variables.basePath}/og/default.png`
}

function readingMinutes(html: string) {
  const words = html
    .replace(/<[^>]+>/g, " ")
    .split(/\s+/)
    .filter(Boolean).length
  return Math.max(1, Math.round(words / WORDS_PER_MINUTE))
}

function toISO(date: string | Date) {
  return typeof date === "string"
    ? new Date(date).toISOString()
    : date.toISOString()
}

export function orderTags(tags: string[]) {
  return Object.entries<number>(
    tags.reduce(
      (acc, tag) => {
        acc[tag] = (acc[tag] || 0) + 1
        return acc
      },
      {} as Record<string, number>,
    ),
  )
    .sort(([v1, c1], [v2, c2]) => c2 - c1 || v1.localeCompare(v2))
    .slice(0, 15)
    .map(([v]) => v)
}
